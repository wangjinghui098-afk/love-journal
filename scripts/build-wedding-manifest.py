def note_for(index: int) -> str:
    if index <= 22:
        return "红妆映着旧庭院，也映着我们崭新的开始。"
    if index <= 29:
        return "一袭白纱，把所有温柔都留给了彼此。"
    if index <= 53:
        return "灯光穿过长廊，而我们的故事才刚刚开始。"
    return "在风经过的地方，牵着彼此走向更远的未来。"


def main() -> None:
    by_index: dict[int, Path] = {}
    for path in WEB_DIR.glob("wedding-*.webp"):
        match = re.fullmatch(r"wedding-(\d{3})\.webp", path.name)
        if match:
            by_index[int(match.group(1))] = path
    if not by_index:
        raise SystemExit("No processed wedding images found.")
    remaining = [
        index for index in sorted(by_index) if index not in set(FEATURED)
    ]
    ordered_indices = FEATURED + remaining
    photos = []
    for index in ordered_indices:
        title = TITLES[index]
        thumb = THUMB_DIR / by_index[index].name
        grid = GRID_DIR / by_index[index].name
        if not thumb.exists():
            raise SystemExit(f"Missing thumbnail: {thumb}")
        if not grid.exists():
            raise SystemExit(f"Missing grid image: {grid}")
        with Image.open(grid) as grid_image:
            grid_width, grid_height = grid_image.size
        with Image.open(thumb) as thumb_image:
            thumb_width, thumb_height = thumb_image.size
        photos.append(
            {
                "src": f"photos/wedding/{by_index[index].name}",
                "thumb": f"photos/wedding/thumbs/{thumb.name}",
                "grid": f"photos/wedding/grid/{grid.name}",
                "gridWidth": grid_width,
                "gridHeight": grid_height,
                "thumbWidth": thumb_width,
                "thumbHeight": thumb_height,
                "title": title,
                "alt": f"{title}，婚纱照",
                "note": note_for(index),
            }
        )

    payload = json.dumps(photos, ensure_ascii=False, indent=2)
    OUTPUT_PATH.write_text(
        "/* Generated by scripts/build-wedding-manifest.py. */\n"
        f"window.WEDDING_PHOTOS = {payload};\n",
        encoding="utf-8",
    )
    print(
        json.dumps(
            {
                "count": len(photos),
                "featured": FEATURED,
                "manifest": str(OUTPUT_PATH),
            },
            ensure_ascii=False,
        )
    )


if __name__ == "__main__":
    main()
